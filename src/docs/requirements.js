export function requirementById(id) {
  return REQUIREMENTS.find((r) => r.id === id) ?? null
}

export function requirementsByFeature() {
  const map = new Map()
  for (const r of REQUIREMENTS) {
    if (!map.has(r.feature)) map.set(r.feature, [])
    map.get(r.feature).push(r)
  }
  return map
}
