// Requirement specification.
//
// Written to the INCOSE Guide for Writing Requirements characteristics:
// each statement is necessary, singular (one "shall", one capability),
// unambiguous, complete, feasible, and verifiable. Statements use active
// voice with the system as subject, avoid vague terms ("appropriate",
// "user-friendly", "as needed", "etc."), and state the condition under
// which the requirement applies where that condition is not universal.
//
// Pattern used:
//   [Condition] the <system> shall <action> <object> <performance>.
//
// Fields:
//   text          the requirement statement itself
//   rationale     why it exists — deliberately kept out of the statement
//   verification  how conformance is demonstrated
//   risks/tests   traceability links, resolved both ways by the matrix
//
// Concept specification for demonstration. Not reviewed, not approved,
// not under change control.

